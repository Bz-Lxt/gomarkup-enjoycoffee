//go:build race

package flavor

// raceEnabled 为真时，NFR-01 的延迟断言会退化成只记录不判定。
//
// 竞态检测器会给每一次内存访问插桩，官方文档给出的开销是 CPU 5–10 倍、
// 内存 5–10 倍。位图筛选正是纯内存访问密集型的工作，实测 P50 从 107µs
// 涨到 2.8ms —— 涨了 26 倍。
//
// 拿这个数字去对 10ms 的预算做判定是没有意义的：NFR-01 承诺的是
// 用户实际感受到的延迟，而用户跑的是不带插桩的生产二进制。
// 若为了让 `go test -race ./...` 变绿而把预算放宽到 40ms，
// 那就等于永久放弃了对真实延迟的约束 —— 生产环境慢四倍也测不出来。
//
// 所以这里的选择是：预算只在无插桩时判定，开着 -race 时仍然跑完全部轮次
// （竞态检测器照样在盯并发问题）并把耗时打进日志，只是不拿它当验收依据。
const raceEnabled = true
